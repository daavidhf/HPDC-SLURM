import sys
import os
import glob
from datetime import datetime

def main():
    # =================================
    # PHASE 4: CONSOLIDATION OF RESULTS
    # =================================

    # Make sure we receive the path to the results folder
    if len(sys.argv) < 2:
        print("Usage: python consolidate_results.py <results_directory_path>")
        sys.exit(1)

    base_dir =os.path.dirname(os.path.abspath(sys.argv[1]))
    results_dir = os.path.join(base_dir, 'results')
    logs_dir = os.path.join(base_dir, 'logs')

    log_file = os.path.join(logs_dir, 'ORCHEST_LOG.txt')
    def register_log(message):
        current_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        full_message = f"[{current_time}] {message}"
        with open(log_file, 'a') as f: # 'a' for append mode without overwriting
            f.write(full_message + '\n')
    
    with open(log_file, 'a') as f: # 'a' for append mode, which will add to the file that already exists
        title = " STARTING PHASE 4: CONSOLIDATION OF RESULTS "
        f.write(f"{title.center(100, '=')}\n")

    # A 'set' in Python does not allow duplicate elements
    all_primes = set()

    # Search for all partial files generated by the SLURM Job Array
    # We assume the orchestrator will name them 'primes_1.txt', 'primes_2.txt', etc.
    partial_files = glob.glob(os.path.join(logs_dir, 'compute_*_*.out'))

    if not partial_files:
        register_log("No partial result files found to consolidate.")
        sys.exit(1)

    register_log(f"Consolidating {len(partial_files)} temporary files...")

    # Read each file and add the numbers to the set
    for file_path in partial_files:
        with open(file_path, 'r') as f: # 'r' for read mode
            for line in f:
                line = line.strip()
                if line.isdigit():
                    all_primes.add(int(line))

    # Convert the set to a list and sort it from lowest to highest
    sorted_primes = sorted(list(all_primes))

    # Write the final file ALL_PRIMES.txt
    final_file = os.path.join(results_dir, 'ALL_PRIMES.txt')
    with open(final_file, 'w') as f:
        for prime in sorted_primes:
            f.write(f"{prime}\n")
        
        # The last line should contain the total number of primes
        f.write(f"TOTAL: {len(sorted_primes)}\n")

    register_log(f"Success: {len(sorted_primes)} unique primes saved in {final_file}")

    with open(log_file, 'a') as f: # 'a' for append mode, which will add to the file that already exists
        title = " STARTING PHASE 4: CONSOLIDATION OF RESULTS "
        f.write(f"{title.center(100, '=')}\n")

if __name__ == '__main__':
    main()
